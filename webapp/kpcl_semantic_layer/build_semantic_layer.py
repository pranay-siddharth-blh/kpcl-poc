"""
Build kpcl_semantic_layer/semantic_layer.json from the warehouse's semantic_* tables and metadata.

The chatbot never writes: this script is run offline after warehouse/build_warehouse.py, and the app
only reads the JSON it produces. Sources (single source of truth):
  kpcl_gms.db  semantic_table_doc / semantic_column_doc / semantic_capability / semantic_data_period
  warehouse/metadata/metric_registry.json, semantic_docs.json (glossary, rules, aliases), known_issues.json

usage (from this folder):  python build_semantic_layer.py [path/to/kpcl_gms.db]
"""
from __future__ import annotations

import hashlib
import json
import pathlib
import sqlite3
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
DB = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "warehouse" / "kpcl_gms.db"
META = ROOT / "warehouse" / "metadata"


def main() -> None:
    con = sqlite3.connect(f"file:{DB.as_posix()}?mode=ro", uri=True)
    docs = json.loads((META / "semantic_docs.json").read_text(encoding="utf8"))
    registry = json.loads((META / "metric_registry.json").read_text(encoding="utf8"))
    issues = json.loads((META / "known_issues.json").read_text(encoding="utf8"))
    caps_meta = {c["topic"]: c for c in json.loads((META / "capability_manifest.json").read_text(encoding="utf8"))["topics"]}

    tables = {}
    for t, group, grain, doc, n, dfrom, dto in con.execute(
            "SELECT table_name, table_group, grain, doc, row_count, date_from, date_to FROM semantic_table_doc ORDER BY table_name"):
        cols = {}
        for c, typ, unit, additive, cdoc in con.execute(
                "SELECT column_name, data_type, unit, additive, doc FROM semantic_column_doc WHERE table_name = ? "
                "ORDER BY rowid", (t,)):
            cols[c] = {"type": typ, "unit": unit, "additive": None if additive is None else bool(additive), "doc": cdoc}
        tables[t] = {"group": group, "grain": grain, "doc": doc, "row_count": n, "date_from": dfrom, "date_to": dto,
                     "columns": cols}

    period = dict(con.execute("SELECT key, value FROM semantic_data_period"))
    capabilities = []
    for topic, status, marts, note in con.execute("SELECT topic, status, mart_tables, note FROM semantic_capability"):
        capabilities.append({"topic": topic, "status": status, "mart_tables": marts.split(",") if marts else [],
                             "keywords": caps_meta.get(topic, {}).get("keywords", []), "note": note})
    stations = [dict(zip(("key", "name", "category", "plant_type", "capacity_mw", "company"), r)) for r in con.execute(
        "SELECT station_key, station_name, plant_category_label, plant_type_code, installed_capacity_mw, company_code "
        "FROM mart_dim_station ORDER BY report_order")]
    units = [dict(zip(("key", "station", "unit_no", "capacity_mw"), r)) for r in con.execute(
        "SELECT unit_key, station_key, unit_no, capacity_mw FROM mart_dim_unit ORDER BY station_key, unit_no")]
    reservoirs = [dict(zip(("key", "name", "level_unit", "feeds"), r)) for r in con.execute(
        "SELECT reservoir_key, reservoir_name, level_unit, feeds_stations FROM mart_dim_reservoir ORDER BY reservoir_key")]
    reasons = [dict(zip(("code", "description", "plant_type", "reason_class"), r)) for r in con.execute(
        "SELECT reason_code, description, plant_type_code, reason_class FROM mart_dim_outage_reason ORDER BY reason_code")]
    suppliers = [dict(zip(("code", "name", "is_imported"), r)) for r in con.execute(
        "SELECT supplier_code, supplier_name, is_imported FROM mart_dim_coal_supplier ORDER BY supplier_code")]
    fys = [r[0] for r in con.execute("SELECT DISTINCT fy FROM mart_dim_date ORDER BY fy")]
    water_years = [r[0] for r in con.execute("SELECT DISTINCT water_year FROM mart_dim_date ORDER BY water_year")]
    month_labels = [r[0] for r in con.execute("SELECT DISTINCT month_label FROM mart_dim_date ORDER BY month_start")]
    con.close()

    layer = {
        "_purpose": "Semantic layer for the KPCL GMS NL2SQL chatbot. Generated by build_semantic_layer.py from the "
                    "warehouse; do not edit by hand. The chatbot reads it; it never writes.",
        "database": "warehouse/kpcl_gms.db (SQLite). The chatbot's SQL may read only mart_* tables.",
        "data_period": period,
        "rules": docs["rules"],
        "glossary": docs["glossary"],
        "metrics": registry["metrics"],
        "non_averageable_columns": registry["non_averageable_columns"],
        "non_summable_columns": registry["non_summable_columns"],
        "tables": tables,
        "capabilities": capabilities,
        "caveats": [{"id": i["id"], "caveat": i["caveat"], "affects": i.get("affects", [])} for i in issues["issues"] if i["caveat"]],
        "entities": {"stations": stations, "units": units, "reservoirs": reservoirs, "reasons": reasons, "suppliers": suppliers, "fiscal_years": fys,
                     "water_years": water_years, "month_labels": month_labels,
                     "station_aliases": docs["station_aliases"], "reservoir_aliases": docs["reservoir_aliases"],
                     "category_aliases": docs["category_aliases"]},
    }
    text = json.dumps(layer, indent=1, ensure_ascii=False)
    (HERE / "semantic_layer.json").write_text(text, encoding="utf8")

    # Locked-inputs manifest: the app must never change these; tests/test_integrity.py re-hashes them.
    def sha(p: pathlib.Path) -> str:
        h = hashlib.sha256()
        with open(p, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        return h.hexdigest()
    locked = [DB, HERE / "semantic_layer.json", HERE / "example_queries.sql"]
    manifest = {"_purpose": "SHA-256 of the files the chatbot only reads; written by build_semantic_layer.py.",
                "files": {p.resolve().relative_to(ROOT.resolve()).as_posix(): sha(p) for p in locked}}
    (HERE.parent / "integrity_manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf8")
    print(f"wrote semantic_layer.json: {len(tables)} tables, {len(registry['metrics'])} metrics, "
          f"{len(capabilities)} capability topics, {len(docs['glossary'])} glossary terms, "
          f"sha256 {hashlib.sha256(text.encode()).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
